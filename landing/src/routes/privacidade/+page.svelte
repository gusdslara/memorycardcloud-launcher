  <h1>Política de privacidade</h1>
  <p>Esta política explica quais dados o MemoryCard.cloud trata e por quê, conforme a Lei Geral de Proteção de Dados (LGPD, Lei 13.709/2018).</p>

  <h2>Dados que coletamos</h2>
  <ul>
    <li><strong>Conta:</strong> nome, e-mail e senha (guardada só como hash).</li>
    <li><strong>Pagamento:</strong> CPF/CNPJ, telefone e endereço de cobrança, enviados ao parceiro de pagamentos para emitir a cobrança. Não guardamos dados de cartão.</li>
    <li><strong>Saves:</strong> os arquivos de save que o app envia para backup, com nome do jogo, plataforma, data e tamanho.</li>
    <li><strong>Aceite dos termos:</strong> data, IP e navegador no momento do cadastro, como registro do consentimento.</li>
    <li><strong>Uso técnico:</strong> registros de acesso do servidor, para segurança e diagnóstico.</li>
  </ul>

  <h2>Para que usamos</h2>
  <p>Para manter sua conta, guardar e restaurar seus saves, cobrar a assinatura, prevenir fraude e cumprir obrigações legais. Não vendemos dados pessoais nem usamos seus saves para publicidade.</p>

  <h2>Compartilhamento</h2>
  <p>Só com o parceiro de pagamentos (para a cobrança) e com provedores de infraestrutura que hospedam o serviço, sempre no limite do necessário.</p>

  <h2>Por quanto tempo</h2>
  <p>Enquanto a conta existir. Se você pedir a exclusão da conta, apagamos os saves e os dados pessoais, exceto o que a lei obriga a manter (como registros fiscais).</p>

  <h2>Seus direitos</h2>
  <p>Você pode pedir acesso, correção, portabilidade ou exclusão dos seus dados, e revogar consentimentos, pelo e-mail <a href="mailto:privacidade@memorycard.cloud">privacidade@memorycard.cloud</a>.</p>

  <h2>Cookies</h2>
  <p>Usamos um único cookie essencial (HttpOnly) para manter você conectado. Não usamos cookies de rastreamento.</p>
