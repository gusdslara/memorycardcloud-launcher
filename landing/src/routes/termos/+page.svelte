  <h1>Termos de uso</h1>

  <h2>1. O serviço</h2>
  <p>O MemoryCard.cloud oferece um aplicativo (launcher e instalador) que baixa ports, recompilações e emuladores das suas fontes oficiais, aplica configurações por aparelho e faz backup dos saves dos seus jogos. O app pode ser usado de graça; o backup na nuvem e a sincronização entre aparelhos fazem parte da assinatura.</p>

  <h2>2. Sua conta</h2>
  <p>Você é responsável pelos dados de acesso da sua conta e pelo que é feito com ela. Use um e-mail válido e uma senha que não usa em outros serviços.</p>

  <h2>3. Jogos, ROMs e BIOS</h2>
  <p>O MemoryCard não vende nem distribui jogos, ROMs, ISOs, BIOS ou chaves de console. Você só deve usar cópias de jogos e arquivos de sistema que possui legalmente. O app apenas localiza esses arquivos no seu aparelho ou armazenamento e os coloca na pasta que cada port ou emulador espera.</p>

  <h2>4. Ports e emuladores de terceiros</h2>
  <p>Cada port e emulador pertence aos seus autores e segue a licença do projeto. O download principal sempre aponta para a release oficial; o mirror do MemoryCard é uma cópia idêntica, verificada por SHA-256, usada só como reserva.</p>

  <h2>5. Assinatura e pagamento</h2>
  <p>A assinatura é mensal ou anual, cobrada por PIX ou cartão pelo nosso parceiro de pagamentos, e renova automaticamente até ser cancelada. O espaço de nuvem de cada plano aparece na página de <a href="/planos/">planos</a>. Ao cancelar, o acesso continua até o fim do período pago, e seus saves continuam disponíveis para download na <a href="/conta/">sua conta</a>.</p>

  <h2>6. Uso aceitável</h2>
  <p>Não use o espaço na nuvem para guardar ou compartilhar conteúdo de terceiros sem autorização, malware ou qualquer coisa ilegal. Podemos suspender contas que violem estes termos.</p>

  <h2>7. Garantias</h2>
  <p>Fazemos o possível para manter o serviço no ar e os backups íntegros, mas ports e emuladores são software de terceiros, e o funcionamento depende do seu aparelho. Mantenha também uma cópia local dos saves importantes.</p>

  <h2>8. Contato</h2>
  <p>Dúvidas sobre estes termos: <a href="mailto:contato@memorycard.cloud">contato@memorycard.cloud</a>.</p>
