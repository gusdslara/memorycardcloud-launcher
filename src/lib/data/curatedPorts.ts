/**
 * Curated catalog of recomps, decomps and source ports.
 *
 * Every entry was checked against the project's latest GitHub release
 * (Oct/2026). Asset names embed version numbers, so instead of hard-coding
 * URLs we store a regex per platform and resolve the newest asset at install
 * time (see installer.rs / installService.ts).
 *
 * Projects without official binaries (sm64ex, Render96ex, WipEout Rewrite,
 * re3/reVC after the DMCA, OoT "recomp" that never existed) were removed so
 * the "Instalar" button never leads to a dead link.
 */
